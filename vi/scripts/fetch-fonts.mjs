/**
 * Downloads the Inter woff2 files (latin + latin-ext) so the site self-hosts its
 * typeface instead of calling fonts.googleapis.com on every visit.
 *
 *   node scripts/fetch-fonts.mjs
 *
 * Writes public/fonts/*.woff2 and prints the @font-face rules to paste into
 * src/styles/fonts.css (already committed — rerun only if the weights change).
 */
import { mkdir, writeFile, stat } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public', 'fonts');
const KEEP = ['latin', 'latin-ext'];
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

await mkdir(OUT, { recursive: true });

const css = await (
  await fetch('https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600;700&display=swap', {
    headers: { 'User-Agent': UA }
  })
).text();

/* Google serves Inter as a variable font: every weight in a subset resolves to
   the same woff2. Keep one file per subset and declare a weight range. */
const bySubset = new Map();
for (const block of css.split(/(?=\/\* )/)) {
  const subset = block.match(/^\/\* ([a-z-]+) \*\//)?.[1];
  if (!subset || !KEEP.includes(subset) || bySubset.has(subset)) continue;

  const url = block.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
  const range = block.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim();
  if (!url) continue;

  const file = `inter-${subset}.woff2`;
  const dest = join(OUT, file);
  let size;
  try {
    size = (await stat(dest)).size;
  } catch {
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    await writeFile(dest, buf);
    size = buf.length;
  }
  bySubset.set(subset, { file, range, size });
  console.log(`${file.padEnd(28)} ${String(size).padStart(7)} bytes`);
}

const faces = [...bySubset.values()];
const rules =
  `/* Generated by scripts/fetch-fonts.mjs — self-hosted so the site makes no\n   third-party font request. Inter is variable: one file covers 300-700. */\n` +
  faces
    .map(
      (f) => `@font-face {
  font-family: 'Inter';
  font-style: normal;
  font-weight: 300 700;
  font-display: swap;
  src: url('/fonts/${f.file}') format('woff2');
  unicode-range: ${f.range};
}`
    )
    .join('\n');

await writeFile(join(ROOT, 'src', 'styles', 'fonts.css'), rules + '\n', 'utf8');
console.log(`\n${faces.length} files, ${(faces.reduce((n, f) => n + f.size, 0) / 1024).toFixed(0)} KB total`);
console.log('wrote src/styles/fonts.css');
